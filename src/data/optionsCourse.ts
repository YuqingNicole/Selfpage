export type ChoiceExercise = {
  type: 'choice';
  question: string;
  options: string[];
  correct: number;
  explain: string;
};

export type TrueFalseExercise = {
  type: 'tf';
  statement: string;
  answer: boolean;
  explain: string;
};

export type FillExercise = {
  type: 'fill';
  before: string;
  after: string;
  options: string[];
  correct: number;
  explain: string;
};

export type MatchExercise = {
  type: 'match';
  prompt: string;
  pairs: [string, string][];
};

export type Exercise = ChoiceExercise | TrueFalseExercise | FillExercise | MatchExercise;

export interface Lesson {
  id: string;
  title: string;
  tips: string[];
  /** 知识卡片中的引导图示 id，见 components/learn/diagrams.tsx */
  diagram?: string;
  /** 生活化比喻，帮助零基础理解 */
  analogy?: string;
  exercises: Exercise[];
  /** 可选的基础版练习；适合第一次接触这个主题的学习者。 */
  simpleExercises?: Exercise[];
}

export interface Unit {
  id: string;
  title: string;
  subtitle: string;
  color: string;
  colorDark: string;
  icon: string;
  lessons: Lesson[];
}

